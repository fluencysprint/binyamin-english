const BY_ID = new Map(phraseCurriculum.map((p) => [p.id, p]))

export function getPhrase(id: string): PhraseTarget | undefined {
  return BY_ID.get(id)
}

export function phrasesForUnit(unit: number): PhraseTarget[] {
  return phraseCurriculum.filter((p) => p.unit === unit)
}

