/* ==========================================================================
   The phrase-first Pre-A1 → early-A1 inventory.
   --------------------------------------------------------------------------
   The beginner bank next door (lessons/beginnerContent.ts) is a set of
   ACTIVITIES: things a tutor can do for four minutes. That was enough to fill
   a lesson and never enough to answer the only question that matters between
   lessons — "which English can this learner actually say?" An activity is not
   a target: it has no meaning, no prerequisites, nothing to be due for review,
   and nothing that can be produced unaided.

   This file is the missing half: one hundred CHUNKS AND SENTENCE FRAMES,
   chosen for what they let a learner do in a real conversation on day one.

   Four rules decided what is in here, in this order:

     1. UTILITY.       Would a real beginner need this in their first month
                       of using English with a human being? "I don't
                       understand" outranks the alphabet.
     2. FREQUENCY.     Spoken frequency, not written. "Really?" earns a slot;
                       "How do you do?" does not.
     3. GENERATIVITY.  A frame with a slot ("I want ___") is worth more than
                       ten memorized sentences, because the learner leaves
                       with a machine rather than a souvenir. 62 of the 100
                       carry a slot on purpose.
     4. TEACHABILITY.  It has to be showable without translation — a gesture,
                       an object, a situation. `show` names which.

   And two things are deliberately absent: grammar terminology (a learner
   meets "I'm going to ___" as one piece of language, never as "the present
   continuous"), and any target whose only value is that it is traditionally
   taught first.

   The ENGLISH here is content the learner hears and says, and is never
   translated. The one localized field is `meaning` — a zero-English learner
   has to be told what a chunk means in a language they have, and every
   locale carries it under `phrase.<id>.meaning`.
   ========================================================================== */

import { PreA1Stage } from '../types'

/** What the chunk lets a learner DO. Drives lesson shape, not vocabulary. */
export type PhraseFunction =
  | 'greeting'
  | 'repair'
  | 'introducing'
  | 'describingSelf'
  | 'wanting'
  | 'asking'
  | 'everyday'
  | 'reacting'
  | 'practical'
  | 'arranging'

/** How the tutor makes the meaning land WITHOUT translating it. */
export type PhraseShow = 'gesture' | 'object' | 'picture' | 'situation' | 'contrast'

export interface PhraseTarget {
  /** Stable forever — evidence, review dates and homework all key on it. */
  id: string
  /**
   * The canonical form the learner stores. `___` marks the substitutable
   * slot: it is the difference between a phrase they can use and a sentence
   * they can recite.
   */
  chunk: string
  /** One complete utterance — what the tutor models and what TTS speaks. */
  say: string
  /** Plain-English meaning. Localized per learner via `phrase.<id>.meaning`. */
  meaning: string
  /** Curriculum unit, 1–10. */
  unit: number
  /** Earliest internal stage this is teachable at. */
  stage: PreA1Stage
  fn: PhraseFunction
  /** Words that fit the slot. Empty for a fixed chunk. */
  slots: string[]
  /** Whole utterances built from the chunk — models, and substitution drill. */
  examples: string[]
  /** Ids that should already be produced with support before this is met. */
  requires: string[]
  /** The natural reply, so the tutor can run a two-line exchange immediately. */
  reply?: string
  show: PhraseShow
  /** Global teaching order. */
  order: number
}

/** Does this target carry a substitutable slot? */
export function isFrame(p: PhraseTarget): boolean {
  return p.chunk.includes('___')
}

/** Fill a frame's slot. A fixed chunk is returned unchanged. */
export function fillSlot(p: PhraseTarget, filler: string): string {
  return p.chunk.includes('___') ? p.chunk.replace('___', filler) : p.chunk
}

